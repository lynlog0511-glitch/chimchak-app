import { cx } from "@/components/utils";

/**
 * 「도입 예정」·「게시 예정」 표 — 아직 열지 않은 항목에 다는 작은 라벨입니다.
 *
 * 이 화면은 「지금 되는 것」과 「설계까지 한 것」이 같은 말투로 섞이면 신뢰를 통째로 잃습니다.
 * /train의 「7종 열림 · 5종 준비 중」과 같은 문법을, 기관 기능 쪽에도 그대로 씁니다.
 *
 * 낱말은 2026-08-30에 「계획」에서 갈랐습니다. 이 화면이 개인정보 처리방침 같은 **안내 문서**
 * 격으로 재편되면서, 내부 일정표의 말(「계획」)이 아니라 읽는 분에게 무엇이 언제 열리는지를
 * 말하는 낱말이 맞기 때문입니다. 어느 낱말을 쓰는지는 아래 `label` 주석의 기준 하나로 정합니다.
 *
 * 공용 `Badge` 대신 여기서 직접 그리는 이유는 **무게** 하나입니다 — 이 라벨은 장식이 아니라
 * 「이건 아직 없습니다」라는 사실이라, 문장에 딸린 칩이 아니라 문장과 같은 급으로 읽혀야 합니다.
 * 그래서 글자색을 ink-soft(약 8.5:1)로 세우고, 크기는 이 화면의 메타 눈금(12.5px)에 맞춥니다.
 */

export interface PlanTagProps {
  className?: string;
  /**
   * 라벨 문구 — 두 낱말을 가르는 기준은 **그 자리에 무엇이 올라오는가** 하나입니다
   * (2026-08-30 확정 · 같은 날 적대 검증 H2에서 실제 분류와 어긋난 자리를 바로잡았습니다).
   *
   *  · 「게시 예정」 — **잰 값이나 문서가 그 자리에 올라올** 항목. 기능은 이미 있고,
   *    아직 없는 것은 결과물뿐입니다. 지금 이 조건에 맞는 자리는 **검증 계단 ④(파일럿)
   *    하나뿐**입니다 — 잴 항목까지 적어 두었고 1차 결과가 나오면 그 칸이 숫자로 찹니다.
   *  · 「도입 예정」 — **기능·권한·절차가 아직 없는** 항목 전부. 이탈 감지 후 되돌리기,
   *    근거 문서 목록 검색, 가명처리 경로의 추론·저장 단, 기관 관리자·운영자 권한,
   *    기록 재전송·유출 대응, 확인서 위조 방지가 여기 듭니다. 이 자리에 올라올 「게시물」은
   *    없습니다 — 만들어져야 하는 것은 기능입니다.
   *
   * 기준을 한 줄로 두는 이유가 이 주석의 전부입니다. 예전 기본값은 「게시 예정」이었고,
   * 그래서 기능이 없는 자리 여섯 곳이 「곧 무언가가 올라온다」로 읽혔습니다.
   */
  label?: "게시 예정" | "도입 예정";
}

/**
 * 기본값은 「도입 예정」입니다 — 이 표가 붙는 자리는 거의 전부 「아직 없는 기능」이고,
 * 「게시 예정」은 검증 계단 ④ 한 곳뿐이라 그쪽이 명시하는 편이 틀리기 어렵습니다.
 */
export function PlanTag({ className, label = "도입 예정" }: PlanTagProps) {
  return (
    <span
      className={cx(
        "inline-flex items-center rounded-chip border border-line-strong px-2 py-[1px]",
        "align-[2px] text-[0.7813rem] leading-[1.45] font-bold whitespace-nowrap text-ink-soft",
        className,
      )}
    >
      {label}
    </span>
  );
}

export default PlanTag;
