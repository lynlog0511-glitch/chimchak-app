import { FIELD_VOICES } from "@/data/fieldVoices";
import { PROTOCOLS } from "@/data/protocols";
import { RUBRIC } from "@/data/rubric";
import { cx } from "@/components/utils";

/**
 * 현직 감수 현황 — **끝난 것과 안 끝난 것을 한자리에** 적습니다.
 *
 * 「현직 감수를 받았습니다」만 적어 두면 어디까지 받았는지 알 수 없고,
 * 진행 중인 것을 완료로 적으면 나머지 기록까지 못 믿게 됩니다. 그래서 두 줄을 같이 놓습니다.
 *
 * 응급 안내 줄은 `src/data/protocols.ts`의 `reviewed` 문자열과 `reviewPending` 표기를 세어서
 * 만듭니다 — 데이터가 바뀌면 이 카드도 같이 바뀝니다(손으로 적은 숫자가 아닙니다).
 * 감수는 세 갈래입니다: 마친 것 · 한 번 보고 다시 보는 중인 것 · **아직 한 번도 안 본 것**.
 * 셋째 갈래(2026-08-30 신설)를 둘째와 같은 말로 묶으면, 이 카드가 스스로 하지 말라고 적어 둔
 * 일(진행 중인 것을 진행된 것처럼 적기)을 한 단 아래에서 다시 하게 됩니다.
 *
 * 감수 **완료본을 고친 사실**도 여기 적습니다. 완료 종수만 세면 화면은 「1종 감수 완료」라고
 * 말하는데, 그 1종이 방금 고쳐져 재확인을 기다리는 중일 수 있습니다. 고친 줄 수도 데이터에서
 * 세고, 날짜만 상수로 둡니다.
 */

export interface ReviewLedgerProps {
  className?: string;
}

/** 감수 완료로 세는 기준 — protocols.ts의 `reviewed`가 「감수 완료」로 시작하는 항목입니다. */
function isReviewed(reviewed: string): boolean {
  return reviewed.startsWith("감수 완료");
}

/**
 * 감수 완료본을 고친 날 — `src/data/protocols.ts` 머리 주석의 수정 기록과 같은 날짜입니다.
 *
 * 고친 줄은 주소 단계 음성이고, 그 안에는 유일한 감수 완료본(P-02)이 들어 있습니다.
 * 화면이 「1종 감수 완료」만 말하고 이 사실을 빼면, 진행 중인 것을 완료로 적는 셈입니다 —
 * 이 카드가 스스로 하지 말라고 적어 둔 일입니다(페르소나 PM low).
 *
 * ※ 이 날 고친 줄을 셀 때 **뒤에 새로 더한 안내는 빼야 합니다**(아래 `revisedLines`).
 *   P-06은 2026-08-30에 처음 쓴 안내라 8/25에 고쳐진 적이 없습니다. 주소 단계를 가졌다는
 *   이유만으로 함께 세면, 이 카드가 「8. 25.에 6줄을 고쳤습니다」라는 없던 사실을 적게 됩니다.
 */
const REVISED_ON = "2026. 8. 25.";

/**
 * 루브릭 완료본을 고친 날 — `src/data/rubric.ts`의 CL-01 교체 사유 주석과 같은 날짜입니다.
 *
 * 이 줄이 왜 있는가: 이 카드는 머리말에 「감수 **완료본을 고친 사실**도 여기 적습니다」라고
 * 자기 규칙을 세워 두었고, 응급 안내 쪽에는 그 규칙대로 「수정 뒤 재확인」 행이 있습니다.
 * 그런데 2026-08-26에 **1차 감수 완료본인 루브릭 30항목 중 CL-01의 지표와 앵커 넷을 전면
 * 개정**하고도 그 사실이 이 원장에 없었습니다 — 화면이 「1차 감수 완료 · 7. 25.」만 말하는
 * 동안, 그 완료본의 한 항목은 개정된 채 재확인을 기다리는 상태였습니다.
 * 심사위원이 「감수는 어떻게 관리합니까」에 이 팀이 내미는 물건이 하필 이 목록입니다
 * (7차 페르소나 PM med).
 *
 * 고친 내용 자체는 옳은 교정입니다 — 채택선이 3요소인데 지표가 「5요소를 모두」라고 적어
 * 한 화면이 세 말을 하던 자리를 없앴습니다(사유 전문은 `rubric.ts`의 CL-01 주석).
 * 여기 적는 것은 그 판단이 아니라 **재확인이 아직 안 끝났다는 사실**입니다.
 */
const RUBRIC_REVISED_ON = "2026. 8. 26.";

/** 개정된 루브릭 항목 — 늘면 이 배열에 더하고, 재확인이 끝나면 비웁니다(빈 배열이면 줄이 사라집니다). */
const RUBRIC_REVISED_IDS: readonly string[] = ["CL-01"];

export function ReviewLedger({ className }: ReviewLedgerProps) {
  const done = PROTOCOLS.filter((p) => isReviewed(p.reviewed));
  /* 「첫 감수 전」과 「2차 감수 대기」는 다른 말입니다 — 앞의 것은 아무도 본 적이 없고,
     뒤의 것은 한 번 본 뒤 다시 보는 중입니다. 세 갈래로 갈라 셉니다. */
  const fresh = PROTOCOLS.filter((p) => p.reviewPending);
  const pending = PROTOCOLS.length - done.length - fresh.length;
  const doneTitles = done.map((p) => p.title).join(" · ");
  /* 고친 줄 수도 데이터에서 셉니다 — 주소를 크게 띄우는 단계가 그 줄을 가진 단계입니다.
     P-06은 그 수정(8/26)보다 뒤에 신설돼 그날 고쳐진 적이 없으므로 이름으로 제외합니다 —
     예전에는 reviewPending이 이 제외를 대신했는데, 감수 확인(8/31)으로 그 표가 내려가면서
     이 셈이 조용히 한 줄을 부풀릴 뻔한 자리입니다. */
  const revisedLines = PROTOCOLS.filter((p) => !p.reviewPending && p.id !== "P-06").reduce(
    (sum, p) => sum + p.steps.filter((step) => typeof step.address === "string").length,
    0,
  );
  /* 개정 항목도 **데이터에 실제로 있는 것만** 셉니다 — 루브릭에서 사라진 id를 화면이 계속
     부르지 않게(응급 안내 줄이 `reviewed`를 세는 것과 같은 규율입니다). */
  const revisedRubricIds = RUBRIC_REVISED_IDS.filter((id) =>
    RUBRIC.some((item) => item.id === id),
  );

  const rows: readonly { k: string; v: string }[] = [
    {
      k: `루브릭 ${RUBRIC.length}항목`,
      v: "1차 감수 완료 — 현직 요양보호사(경력 5년) · 2026. 7. 25.",
    },
    /* 개정된 항목이 없어지면(재확인이 끝나면) 이 줄도 함께 사라집니다 — 응급 안내 쪽 「수정 뒤
       재확인」 행과 같은 문법입니다. 항목 수도 데이터가 아니라 위 목록에서 셉니다. */
    ...(revisedRubricIds.length > 0
      ? [
          {
            k: "루브릭 수정 뒤 재확인",
            v: `${RUBRIC_REVISED_ON} 1차 감수 완료본 가운데 ${revisedRubricIds.length}항목(${revisedRubricIds.join(" · ")})의 지표와 앵커를 고쳤습니다. 채택선이 3요소인데 지표가 「5요소를 모두」라고 적어 한 화면이 세 말을 하던 자리를 없앤 교정이며, 고친 항목은 현직 재확인을 기다립니다.`,
          },
        ]
      : []),
    /* 8/31 확인 사건의 닻 행 — 아래 개별 행들이 「현직 2인 확인」이라고 짧게 적을 때
       그 확인이 무엇이었는지를 이 한 줄이 답합니다. */
    {
      k: "현직 감수 채널",
      v: "2026. 8. 31. 현직 요양보호사 2인(5년차 이상)이 신설분(위험 판단 시나리오 · 문 잠김 응급 안내 · 인물 소개 · 인지 단계 서술)의 문면을 확인했습니다. 같은 날 전문가 교차 재검증(응급구조·현직·교육 관점)이 짚은 자리를 고쳐 반영했고, 센터장 감수가 예정되어 있습니다.",
    },
    {
      k: "시나리오 대사",
      v: "먼저 연 3종은 2차 교차 감수가 진행 중이며, 아직 끝나지 않았습니다. 뒤에 더한 3종(CHK-A02·CHK-B01·CHK-C02)은 초안으로, 현직 감수 대기 상태임을 훈련 브리핑에도 그대로 적었습니다. 2026. 8. 30. 현장 인터뷰 사례를 반영해 위험 판단 유형 1종(CHK-D01 — 방문 시 무응답·문 잠김)을 새로 열었고, 2026. 8. 31. 현직 요양보호사 2인이 확인했습니다 — 같은 날 교차 재검증이 잡은 두 자리(신고를 말한 답의 오판정 · 개문 주체를 한 기관으로 좁힌 단정)도 고쳤습니다.",
    },
    {
      k: "인물 소개 12인",
      v: "2026. 8. 30. 현장 인터뷰의 표현력 지적을 반영해 여섯 시나리오 열두 인물의 소개에 인지·정서 서술 한 문장씩을 더했습니다. 의학 등급 단정 없이 행동 서술로만 적었으며, 2026. 8. 31. 현직 2인이 확인했습니다. 이 문장은 대사 변주 요청의 인물 소개 칸에 함께 실립니다.",
    },
    /* 아래 세 줄은 2026-08-30에 더한 것들입니다. 셋을 한 낱말로 묶지 않는 이유는 **감수와의
       관계가 서로 다르기 때문**입니다: 첫째는 새로 쓴 문장이라 감수를 기다리고, 둘째는 새 문장이
       없는 표시 변경이라 기다릴 것이 없으며, 셋째는 녹취 축자라 애초에 감수로 고칠 수 있는
       물건이 아닙니다. 셋을 「8. 30. 추가」로 뭉뚱그리면 이 카드가 스스로 하지 말라고 적어 둔
       일(상태가 다른 것을 같은 말로 적기)을 다시 하게 됩니다. */
    {
      k: "자유 연습 어르신 인지 단계 서술",
      v: "2026. 8. 30. 현장 인터뷰 제언을 반영해 자유 연습 화면에 어르신의 인지 단계를 적은 서술을 새로 더했고, 2026. 8. 31. 전문가 교차 재검증이 중기·말기 서술을 임상 관찰에 맞게 고쳤으며(옛 말기 서술은 방향이 반대였습니다) 같은 날 현직 2인이 확인했습니다. 연습 상황을 고르실 때 무엇을 가정하고 말할지 정하는 데 쓰는 서술이고, 판정 기준에는 들어가지 않습니다.",
    },
    {
      k: "훈련 마침 화면 항목별 자세히 보기 — 표시 확장",
      v: "2026. 8. 30. 훈련을 마친 화면에서 항목별로 무엇이 어떻게 판정되었는지 펴 볼 수 있게 했습니다. 새로 쓴 문장은 없습니다 — 이미 있던 검수 문구와 항목표를 접어 두었다가 펴는 표시 변경이라, 각 문구의 감수 상태는 원래 가진 그대로입니다. 그래서 이 줄은 감수 대기가 아니라 변경 사실로 적습니다.",
    },
    /* 인용 건수도 데이터에서 셉니다 — 인용이 늘거나 빠지면 이 줄의 숫자도 함께 바뀌고,
       한 건도 없으면 줄이 사라집니다(응급 안내 쪽 조건부 행들과 같은 문법입니다). */
    ...(FIELD_VOICES.length > 0
      ? [
          {
            k: `기관 화면 인터뷰 인용 ${FIELD_VOICES.length}건`,
            v: `2026. 8. 30. 기관 도입 안내 화면에 현장 경험자 심층 인터뷰의 녹취 축자 ${FIELD_VOICES.length}건을 실었습니다. 유상으로 진행한 인터뷰이고, 인용에 관한 서면 동의를 받아 익명으로 옮겼습니다. 축자는 말줄임과 띄어쓰기까지 원문 그대로 두고 표준어로 고치지 않으며, 참여자를 식별할 수 있는 표기는 부호를 포함해 어느 화면에도 싣지 않습니다. 다섯 분의 말이 현장 전체를 대표하지는 않는다는 한계는 인용과 같은 자리에 적었습니다.`,
          },
        ]
      : []),
    {
      k: `응급 안내 ${PROTOCOLS.length}종`,
      v:
        done.length > 0
          ? `${done.length}종 감수 완료 — ${doneTitles} · 나머지 ${pending}종은 2차 감수 대기`
          : `${PROTOCOLS.length - fresh.length}종 모두 2차 감수 대기`,
    },
    /* 새로 더한 안내가 없어지면(첫 감수가 끝나면) 이 줄도 함께 사라집니다 — 위 줄이
       「나머지는 2차 감수 대기」라고만 말하면, 한 번도 감수를 받지 않은 안내가 「한 번 보고
       다시 보는 중」인 것들 사이에 조용히 섞입니다. 종수도 제목도 데이터에서 셉니다. */
    ...(fresh.length > 0
      ? [
          {
            k: `응급 안내 신설 ${fresh.length}종 — 첫 감수 전`,
            v: `${fresh.map((p) => `${p.id} ${p.title}`).join(" · ")}. 2026. 8. 30. 현장 인터뷰 사례를 반영해 새로 더한 안내이며, 아직 현직 감수를 한 번도 받지 않았습니다. 응급 안내 목록과 해당 안내 화면에 「전문가 검토를 받고 있어요」를 그대로 적어 두었습니다. 고정 문구 재생·생성 0건 원칙은 나머지와 똑같이 적용됩니다.`,
          },
        ]
      : []),
    /* 고친 줄이 없어지면(주소 단계가 사라지면) 이 줄도 함께 사라집니다 — 화면이
       「0줄을 고쳤습니다」라고 말하지 않게. */
    ...(revisedLines > 0
      ? [
          {
            k: "응급 안내 수정 뒤 재확인",
            v:
              `${REVISED_ON} 주소 단계 음성 ${revisedLines}줄을 고쳤습니다. 방문지 주소를 미리 적어 두지 않으신 분께도 참이 되도록 바꾼 문장입니다. ` +
              (done.length > 0
                ? `감수 완료본도 이 ${revisedLines}줄에 들어 있어, 지금은 현직 재확인을 기다립니다.`
                : "고친 줄은 모두 현직 재확인을 기다립니다."),
          },
        ]
      : []),
  ];

  return (
    <section
      aria-labelledby="review-ledger-title"
      className={cx("rounded-card bg-paper-2 p-4", className)}
    >
      <h3 id="review-ledger-title" className="text-[1.0625rem] leading-[1.45] font-extrabold text-ink">
        현직 감수 현황
      </h3>

      <dl className="chim-hairline mt-3 border-y border-line">
        {rows.map((row) => (
          <div key={row.k} className="py-3">
            <dt className="text-[0.9375rem] leading-[1.45] font-bold text-ink">{row.k}</dt>
            <dd className="mt-1 text-[0.9375rem] leading-[1.6] text-ink-soft">{row.v}</dd>
          </div>
        ))}
      </dl>

      <p className="mt-3 text-[0.7813rem] leading-[1.6] text-ink-muted">
        끝난 것과 안 끝난 것을 같이 적습니다. 진행 중인 것을 완료로 적어 두면, 이 화면의 나머지
        기록도 믿을 수 없게 됩니다.
      </p>
    </section>
  );
}

export default ReviewLedger;
