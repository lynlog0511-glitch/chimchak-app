/**
 * 현장의 말 — 심층 인터뷰 녹취 축자입니다.
 *
 * 출처 · 2026년 8월, 현장 경험자 다섯 분과 진행한 심층 인터뷰입니다. 유상으로 진행했고,
 * 인용에 관한 서면 동의를 받았으며, 익명으로 옮깁니다. 이 파일은 2026-08-30에 새로 열었고,
 * 인용을 세운 기관 화면은 첫 현직 감수 전입니다.
 *
 * ── 축자 원칙 ────────────────────────────────────────────────
 * **한 글자도 고치지 않습니다.** 말줄임과 띄어쓰기까지 녹취 그대로 두고, 표준어로 다듬거나
 * 문장을 매끄럽게 잇지 않습니다. 붙여 쓰는 것이 맞는 낱말이 띄어 적혀 있어도 그대로입니다 —
 * 고치는 순간 이것은 인용이 아니라 우리가 쓴 문장이 되고, 화면이 「들은 말」이라고 적어 둔
 * 자리가 거짓이 됩니다. 다듬고 싶은 자리가 보이면 인용을 고치는 대신 옆의 `context`를
 * 고칩니다. 그쪽이 우리가 쓰는 문장입니다.
 *
 * 개작을 막는 것은 이 주석이 아니라 `tests/fieldVoices.test.ts`입니다 — 정본 문자열을 그쪽에
 * 따로 한 벌 적어 두어, 이 파일만 고치면 검사가 걸립니다.
 *
 * ── 대표성 한계 ──────────────────────────────────────────────
 * 다섯 분의 말이고, 특정 지역에서 들었습니다. 현장 전체를 대표하지 않습니다. 인용을 싣는
 * 화면은 이 한계를 인용과 **같은 자리에** 적습니다(`FIELD_VOICE_BASIS`) — 한계를 다른 절로
 * 미루면, 읽는 분이 인용만 보고 일반화한 뒤 그 절에 닿지 않습니다.
 *
 * ── 참여자 식별 정보 ─────────────────────────────────────────
 * 실명·소속·지역은 물론 「참여자 A」 같은 부호도 어느 화면에도 싣지 않습니다. 부호는 익명처럼
 * 보이지만 인용이 늘수록 한 사람의 말이 한 부호로 묶이고, 그 묶음을 다른 정보와 맞추면 누구인지
 * 좁혀집니다. 그래서 아래 `id`는 **인용을 가리키는 이름일 뿐 사람을 가리키지 않으며**, 화면에
 * 나가지 않습니다(목록의 key로만 씁니다).
 */

export interface FieldVoice {
  /** 인용 식별자 — 화면에 나가지 않습니다. 사람이 아니라 인용을 가리키는 이름입니다. */
  id: string;
  /** 녹취 축자 — 고치지 않습니다(위 축자 원칙). 낫표는 화면이 이 문장에만 답니다. */
  quote: string;
  /** 무슨 말인지 한 줄 — 우리가 쓴 서술문입니다. 인용이 아니므로 낫표를 달지 않습니다. */
  context: string;
}

