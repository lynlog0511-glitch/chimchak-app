export interface RuleCheckOptions {
  /** 시나리오 유형 — 유형 한정 규칙(예: 기도폐쇄 관련)이 엉뚱한 시나리오에서 발동하지 않게 한다 */
  scenarioType?: ScenarioType;
  /** 현재 CUE id — 세션 국면 게이트(skipCues)에 쓴다 */
  cueId?: string;
  /**
   * 시나리오의 적용 루브릭 항목 목록(설계서 §4.5).
   * 넘기면, 여기에 없는 ⚑CF 항목은 인터럽트 대신 코칭으로 강등한다.
   */
  appliedRubric?: string[];
}

export interface CriticalCheck {
  /** ⚑CF 여부 */
  cf: boolean;
  /** 화면에 띄울 고정 문구 */
  reason?: string;
  docId?: string;
  ruleId?: string;
  itemId?: string;
  label?: string;
  matched?: string;
  alternatives?: string[];
}

/**
 * ⚑CF 판정 — classify 보다 **먼저** 호출한다.
 *
 * @example
 * checkCritical("문을 잠그겠습니다").cf;                              // true
 * checkCritical("문을 잠그지 않겠습니다").cf;                         // false
 * checkCritical("물 좀 드세요", { scenarioType: "EMERGENCY" }).cf;    // true
 * checkCritical("물 좀 드세요", { scenarioType: "BPSD" }).cf;         // false
 */
export function checkCritical(utterance: string, opts: RuleCheckOptions = {}): CriticalCheck {
  if (!utterance || utterance.trim().length === 0) return { cf: false };
  for (const rule of CRITICAL_RULES) {
    if (!applies(rule, opts)) continue;
    if (!inAppliedRubric(rule, opts.appliedRubric)) continue;
    const hit = findTerm(utterance, termsFor(rule, opts), rule.except);
    if (hit) {
      return {
        cf: true,
        reason: rule.message,
        docId: rule.docId,
        ruleId: rule.id,
        itemId: rule.itemId,
        label: rule.label,
        matched: hit.term,
        alternatives: rule.alternatives,
      };
    }
  }
  return { cf: false };
}

/**
 * 시나리오 ⚑CF 분기가 세우는 **한 겹 더** — 사전이 예외어 「이끌」로 놓치는 자리.
 *
 * 4차가 세운 이중 안전망은 「규칙 사전이 놓치면 시나리오 분기가 받는다」였습니다. 그런데
 * 자유 연습(/practice)에는 시나리오도 CUE도 없어 분기가 아예 존재하지 않고, 학습자 발화를
 * 재는 것은 사전 한 겹뿐이었습니다 — 훈련에서는 노인복지법 고지와 대안 3개를 받고 멈춰
 * 서는 문장이 자유 연습에서는 그냥 지나갔습니다(현직·PM 5차). 판정이 갈리는 것이 아니라
 * **같은 문장이 한 화면에서는 ⚑CF, 다른 화면에서는 무사통과**인 것이 문제였습니다.
 *
 * 사전 원본(`RESTRAINT_EXCEPT_TERMS`·`RESTRAINT_RULES.terms`)은 레드팀 경계 케이스로
 * 못 박혀 있어 손대지 않습니다. 대신 분기가 쓰는 신호·예외를 그대로 재사용해 **위에 한 겹**을
 * 올립니다. 돌려주는 값의 모양은 `checkCritical`과 같아, 화면은 두 자리를 구분하지 않습니다.
 *
 * @example checkBranchRestraint("어머님 팔을 잡아 이끌고 나가겠습니다").cf; // true
 * @example checkBranchRestraint("어머님, 제 팔 붙잡으세요").cf;             // false
 */
export function checkBranchRestraint(utterance: string, opts: RuleCheckOptions = {}): CriticalCheck {
  if (!utterance || utterance.trim().length === 0) return { cf: false };
  const rule = RESTRAINT_RULES[0];
  if (!rule) return { cf: false };
  if (!applies(rule, opts)) return { cf: false };
  if (!inAppliedRubric(rule, opts.appliedRubric)) return { cf: false };
  const hit = findTerm(utterance, RESTRAINT_BRANCH_SIGNALS, RESTRAINT_EXCEPT_BRANCH);
  if (!hit) return { cf: false };
  return {
    cf: true,
    reason: rule.message,
    docId: rule.docId,
    ruleId: rule.id,
    itemId: rule.itemId,
    label: rule.label,
    matched: hit.term,
    alternatives: rule.alternatives,
  };
}

export interface AdvisoryFinding {
  ruleId: string;
  itemId: string;
  label: string;
  message: string;
  docId?: string;
  score: 1 | 2;
  matched: string;
}

/** 문장 단위로 잘라 준다 (종결어미 뒤에서도 끊는다) */
function splitSentences(text: string): string[] {
  return text
    .replace(/(습니다|했어요|해요|하세요|입니다|이에요|예요|네요|더라고요)(?=\s|$)/g, "$1.")
    .split(/[.!?\n]+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

function findBanmalEnding(text: string): string | null {
  for (const sentence of splitSentences(text)) {
    const tail = normalize(sentence);
    for (const ending of BANMAL_ENDINGS) {
      const norm = normalize(ending);
      if (norm.length > 0 && tail.endsWith(norm)) return ending;
    }
  }
  return null;
}

/**
 * ⚑CF는 아니지만 루브릭에 반영해야 하는 위반을 모은다.
 * (현실 직면 강요·반말/호칭·개인정보 노출·등 강타)
 *
 * @example
 * checkAdvisory("여기가 집이에요").map(f => f.itemId); // ["RE-02"]
 * checkAdvisory("같이 앉아 계실까요?");                 // []
 */
export function checkAdvisory(utterance: string, opts: RuleCheckOptions = {}): AdvisoryFinding[] {
  const out: AdvisoryFinding[] = [];
  if (!utterance || utterance.trim().length === 0) return out;

  for (const rule of COACHING_RULES) {
    if (rule.terms.length === 0) continue;
    if (!applies(rule, opts)) continue;
    // 코칭 규칙에는 아직 complyOnlyCues가 없어 termsFor()는 rule.terms를 그대로 돌려준다.
    // 그래도 직접 rule.terms를 읽지 않는다 — 어느 규칙에 국면 게이트를 다는 날,
    // 판정(checkCritical)은 좁힌 사전을 쓰고 코칭만 넓은 사전을 쓰는 어긋남이 생긴다.
    const hit = findTerm(utterance, termsFor(rule, opts), rule.except);
    if (hit) {
      out.push({
        ruleId: rule.id,
        itemId: rule.itemId,
        label: rule.label,
        message: rule.message,
        docId: rule.docId,
        score: rule.score,
        matched: hit.term,
      });
    }
  }

  // 설계서 §4.5에서 이 시나리오에 배정되지 않은 ⚑CF 항목은 인터럽트 대신 코칭으로 남긴다.
  // (안내는 사라지지 않고, '치명적 실패' 낙인만 걷어 낸다 — §3.3 판정선 분리)
  // 국면 게이트는 여기서도 그대로 받는다 — 강등된 자리에서도 회고 진술은 행위가 아니다.
  for (const rule of CRITICAL_RULES) {
    if (!applies(rule, opts)) continue;
    if (inAppliedRubric(rule, opts.appliedRubric)) continue;
    const hit = findTerm(utterance, termsFor(rule, opts), rule.except);
    if (hit) {
      out.push({
        ruleId: rule.id,
        itemId: rule.itemId,
        label: rule.label,
        message: rule.message,
        docId: rule.docId,
        score: 2,
        matched: hit.term,
      });
    }
  }

  const banmal = findBanmalEnding(utterance);
  if (banmal && !out.some((f) => f.itemId === "CO-07")) {
    const rule = getRule("WARN-BANMAL");
    if (rule) {
      out.push({
        ruleId: rule.id,
        itemId: rule.itemId,
        label: rule.label,
        message: rule.message,
        docId: rule.docId,
        score: rule.score,
        matched: banmal,
      });
    }
  }

  const pii = maskSpansOnOriginal(utterance).filter((s) => s.kind === "번호" || s.kind === "주소" || s.kind === "생년");
  const firstPii = pii[0];
  if (firstPii) {
    const rule = getRule("WARN-PII");
    if (rule) {
      out.push({
        ruleId: rule.id,
        itemId: rule.itemId,
        label: rule.label,
        message: rule.message,
        docId: rule.docId,
        score: rule.score,
        matched: firstPii.kind,
      });
    }
  }

  return out;
}

/**
 * 코칭 규칙 결과를 루브릭 반영 형태로 바꾼다.
 *
 * @example
 * advisoryHits(checkAdvisory("여기가 집이에요")); // [{ itemId: "RE-02", score: 2 }]
 */
export function advisoryHits(findings: AdvisoryFinding[]): RubricHit[] {
  return findings.map((f) => ({ itemId: f.itemId, score: f.score }));
}

/**
 * 발화에 개인정보로 볼 만한 요소가 있는지 확인한다 (CO-08 보조).
 *
 * @example
 * containsPii("010-1234-5678로 연락 주세요"); // true
 */
export function containsPii(utterance: string): boolean {
  return maskSpansOnOriginal(utterance).some((s) => s.kind !== "성명");
}
