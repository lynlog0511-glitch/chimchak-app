/**
 * 표지 뒤 어딘가에 **부정을 동반하지 않은** 실행 선언이 있는가.
 * ("그렇게 하지 않았습니다"의 「그렇게하」는 곧바로 「않」이 받으므로 실행이 아니다.)
 */
function executionFollows(tail: string): boolean {
  for (const word of EXECUTION_AFTER) {
    let from = 0;
    for (;;) {
      const at = tail.indexOf(word, from);
      if (at < 0) break;
      const between = tail.slice(0, at);
      const rest = tail.slice(at + word.length, at + word.length + EXECUTION_NEGATED_WINDOW);
      if (
        !EXECUTION_BLOCKED_BETWEEN.some((n) => between.includes(n)) &&
        !EXECUTION_NEGATED.some((n) => rest.includes(n))
      ) {
        return true;
      }
      from = at + 1;
    }
  }
  return false;
}

