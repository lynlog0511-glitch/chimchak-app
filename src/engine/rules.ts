/* ── 정규화 ────────────────────────────────────────────── */

const PUNCTUATION = /[.,!?~·…()[\]{}<>:;"'`\-–—/\\|*]/g;

/**
 * 판정용 정규화 — 공백·구두점 제거 + 소문자화.
 *
 * @example
 * normalize("문을  잠그겠습니다."); // "문을잠그겠습니다"
 */
export function normalize(text: string): string {
  return text.normalize("NFC").toLowerCase().replace(/\s+/g, "").replace(PUNCTUATION, "");
}

/* ── 한글 수사 시각 ─────────────────────────────────────── */

/**
 * 시(時)에 쓰는 고유어 수사. 긴 것부터 본다 — 「열두」가 「열」보다 먼저 걸려야 한다.
 */
const NATIVE_HOURS: readonly (readonly [string, number])[] = [
  ["열두", 12],
  ["열한", 11],
  ["아홉", 9],
  ["여덟", 8],
  ["일곱", 7],
  ["여섯", 6],
  ["다섯", 5],
  ["열", 10],
  ["네", 4],
  ["세", 3],
  ["두", 2],
  ["한", 1],
];

/** 분(分)에 쓰는 한자어 십 단위 */
const SINO_TENS: Readonly<Record<string, number>> = {
  십: 10,
  이십: 20,
  삼십: 30,
  사십: 40,
  오십: 50,
};

/** 분(分)의 일 단위 — 십 단위와 **함께 올 때만** 읽는다(아래 주석 참조) */
const SINO_UNITS: Readonly<Record<string, number>> = {
  일: 1,
  이: 2,
  삼: 3,
  사: 4,
  오: 5,
  육: 6,
  칠: 7,
  팔: 8,
  구: 9,
};

/**
 * 「시」 뒤에 와도 시각으로 읽는 조사·의존명사의 첫 글자.
 * 이 글자가 아닌 한글이 이어지면 다른 낱말이다("한시름"·"세시봉").
 */
const HOUR_TAIL = "쯤경반에까부께간였이인가는도만정무넘요";

const HOUR_RE = new RegExp(
  `(^|[^가-힣0-9])(${NATIVE_HOURS.map(([w]) => w).join("|")})\\s*시(?![가-힣])|` +
    `(^|[^가-힣0-9])(${NATIVE_HOURS.map(([w]) => w).join("|")})\\s*시(?=[${HOUR_TAIL}])`,
  "g",
);

/* 「분」은 **십 단위가 있을 때만** 읽는다. 일 단위 홑낱말을 함께 받으면 「이 분」·「그 분」
   같은 사람 지칭이 「2분」이 된다 — 공백을 지우고 나면 「이분」과 글자가 같아 가를 수 없다.
   현장 보고의 분은 대부분 십 단위로 말해진다("사십 분"·"이십오 분"). */
const MINUTE_RE = new RegExp(
  `(^|[^가-힣0-9])(${Object.keys(SINO_TENS).sort((a, b) => b.length - a.length).join("|")})` +
    `\\s*(${Object.keys(SINO_UNITS).join("|")})?\\s*분`,
  "g",
);

/**
 * 판정 **전에** 한글 수사로 말한 시각을 숫자로 바꾼다 — "네 시 사십 분" → "4시 40분".
 *
 * 현장에서는 숫자를 한글로 먼저 말합니다(현직 검증 실측). 5요소를 다 담아 보고했는데
 * 시각 표지(「16시」·「4시 4」·「오후 4시」)에 글자가 닿지 않아 「부분 보고」로 떨어지면,
 * 배우는 것은 무엇을 빠뜨렸는가가 아니라 기계가 무엇을 못 알아듣는가가 됩니다.
 *
 * **normalize() 안에 넣지 않았습니다.** 규칙 사전의 신호·예외어도 같은 함수를 지나가는데,
 * 「한 잔 무」·「한 알」처럼 수사가 낱말의 일부인 항목이 그 자리에서 「1잔 무」로 바뀝니다.
 * 이 변환은 **학습자 발화 한 쪽에만** 겁니다(classify.ts의 classifyInput).
 *
 * @example
 * expandKoreanTimeNumerals("네 시 사십 분쯤에");  // "4시 40분쯤에"
 * expandKoreanTimeNumerals("한시름 놓았습니다");   // 그대로 — 「시」 뒤가 다른 낱말이다
 */
export function expandKoreanTimeNumerals(text: string): string {
  const hours = new Map(NATIVE_HOURS);
  return text
    .replace(HOUR_RE, (_m, lead1: string | undefined, word1: string | undefined, lead2: string | undefined, word2: string | undefined) => {
      const lead = lead1 ?? lead2 ?? "";
      const word = word1 ?? word2 ?? "";
      return `${lead}${hours.get(word) ?? word}시`;
    })
    .replace(MINUTE_RE, (_m, lead: string, tens: string, unit: string | undefined) => {
      const value = SINO_TENS[tens] + (unit ? SINO_UNITS[unit] : 0);
      return `${lead}${value}분`;
    });
}

