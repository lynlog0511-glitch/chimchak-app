/**
 * 부정 표현 — 매치 앞에 붙으면 발동시키지 않는다 (경상 "몬 붙잡습니더"까지).
 *
 * **「절대·절대로·결코」는 뺐다.** 이 셋은 부정어가 아니라 **강조 부사**다. 부정문에 자주
 * 붙을 뿐이라 앞자리에 서 있다는 것만으로 면죄하면, 같은 부사를 붙인 실행 선언이 전 동사에
 * 걸쳐 통째로 빠져나간다("절대 붙잡겠습니다"·"절대 밀치겠습니다"·"절대로 잠급니다").
 * 값은 거의 없다 — 이 부사가 붙은 정상 거절은 예외 없이 「안/못/지 않」을 함께 달고 있어
 * 다른 표지가 이미 받는다("절대 붙잡지 않겠습니다"는 뒤의 「않」이 받는다).
 */
const NEGATION_BEFORE = ["안", "못", "몬"];

/**
 * 매치 지점이 부정·금지 문맥 안에 있는지.
 * (분류기(classify.ts)도 ⚑CF 분기 대조에 이 함수를 그대로 쓴다.)
 *
 * @example
 * isNegated(normalize("밀지 않겠습니다"), 0, 1);            // true
 * isNegated(normalize("문을 잠그면 위험하지 않겠죠"), 0, 3); // false — 잠그겠다는 말이다
 * isNegated(normalize("가두고 싶은 마음이 커서 오늘부터 그렇게 합니다"), 0, 2); // false — 실행 선언이다
 */
export function isNegated(normalized: string, start: number, end: number): boolean {
  let after = normalized.slice(end, end + NEGATION_WINDOW);
  for (const cancel of NEGATION_CANCELS) after = after.split(cancel).join("");
  for (const marker of NEGATION_MARKERS) {
    if (!after.includes(marker)) continue;
    if (REFLECTIVE_MARKERS.includes(marker)) {
      // 돌아보는 표지는 **뒤에 실행이 붙으면** 무효다. 취소어를 지운 뒤의 위치가 아니라
      // 원문에서의 자리를 다시 찾아, 그 표지부터 문장 끝까지를 본다.
      const at = normalized.indexOf(marker, end);
      if (at >= 0 && executionFollows(normalized.slice(at))) continue;
    }
    return true;
  }
  const before = normalized.slice(Math.max(0, start - 4), start);
  return NEGATION_BEFORE.some((n) => before.endsWith(n));
}

