/**
 * **갱신만 받는** 낡은 표식의 창 수 — 최대 서른여섯 창(6시간)까지.
 *
 * 왜 두 수를 가르는가: 갱신 헤더를 「표식을 들고 온 요청」에만 내주기로 하면서(위 주석), 그
 * 규칙만으로는 3차에 닫은 결함이 절반 되살아난다 — 탭을 열어 둔 채 아무 호출도 하지 않으면
 * 화면이 든 표식이 창을 넘고, 그 뒤로는 표식이 없어 갱신도 못 받아 **영영 작은 통**에 남는다.
 * 그래서 이 범위의 낡은 표식은 **작은 통을 쓰되 갱신 표식은 받는다.** 훈련은 이어지고, 표식을
 * 한 번도 가진 적 없는 스크립트는 여전히 아무것도 받지 못한다.
 *
 * ── 이 창을 **넘긴** 화면에는 회복 경로가 없다 (2026-08-27에 적는다) ──
 * 6차는 이 값을 2에서 6으로 올리면서 「영영 작은 통」을 닫았다고 적었지만, 실제로 한 일은
 * **절벽을 20분에서 60분으로 옮긴 것**이고 그 잔여가 어느 주석에도 없었다(7차 페르소나 백엔드 med).
 * 실측으로 확인한 경로는 이렇다: 창을 넘기면 화면이 표식을 스스로 걷고(`onlineCoach.ts`의
 * `readCoachToken`), 무표식 요청에는 갱신 헤더가 붙지 않으며(`route.ts`의 `refreshHeader`),
 * 화면이 든 두 후보(모듈 캐시 `refreshed`와 `<meta>`)는 둘 다 그보다 더 낡아 다시 유효해질 수
 * 없다. **즉 다음 유효 응답이라는 것이 존재하지 않는다** — 이 앱은 앱 안 라우팅만 하므로 문서가
 * 다시 그려지는 일은 사용자가 새로고침할 때뿐이다.
 *
 * 그 회복 경로를 여는 길은 둘뿐이었다.
 *   ⓐ 무표식 요청에도 갱신 헤더를 내준다 → **기각.** 그것이 3차에 닫은 「1회 통행료」 구멍이다
 *      (몸통이 틀린 30바이트 POST 한 번의 400 응답에서 표식이 나오던 자리).
 *   ⓑ 창을 무대 하루가 덮이는 크기로 넓힌다 → 채택.
 * ⓑ의 보안 손실이 사실상 0인 이유: stale 갈래는 이미 **작은 통**을 쓰므로 예산 이득이 없고,
 * 이 갈래가 파는 것은 「이 배포가 내준 표식을 들고 있다」는 증거 하나이며, 그 증거를 처음 얻는
 * 길은 여전히 페이지를 받는 것 하나다. 창을 넓혀도 어긋난 표식 한 건이 태우는 HMAC 수는
 * 아래 캐시가 이 값보다 크므로 워밍업 뒤 0으로 남는다.
 * 36창 = 6시간은 「아침에 연 탭으로 오후 시연까지」를 덮는 크기다. 그보다 낡은 표식은 그대로
 * 403이므로, **절벽 자체가 사라진 것은 아니고 무대 하루 밖으로 밀려났다** — 이 문장을 지우지 말 것.
 *
 * 화면 쪽(`src/lib/onlineCoach.ts`)이 보내는 창 수도 이 값을 본다 — 두 자리가 갈라지면 화면이
 * 스스로 걷어 낸 표식을 서버가 기다리는 일이 생긴다.
 */
export const COACH_TOKEN_STALE_WINDOWS = 36;

/** 토큰 길이(16진 문자 수) — HMAC 앞부분만 쓴다. 헤더 한 칸에 담기는 크기로 족하다. */
export const COACH_TOKEN_LENGTH = 16;

/** 지금이 몇 번째 창인가. */
export function coachTokenWindow(now: number = Date.now()): number {
  return Math.floor(now / COACH_TOKEN_WINDOW_MS);
}

function toHex(buffer: ArrayBuffer): string {
  let out = "";
  for (const byte of new Uint8Array(buffer)) out += byte.toString(16).padStart(2, "0");
  return out;
}

/**
 * 창 하나의 값을 다시 계산하지 않기 위한 아주 작은 기억 자리(인스턴스 메모리).
 *
 * 왜 두는가: 대조 창이 넓어지면서, 어긋난 표식 하나가 요청당 HMAC을 창 수만큼 태우는 자리가
 * 생겼다(그 경로는 예산을 쓰지 않는다 — 값이 어긋난 요청에 예산을 물리면 표식을 아무렇게나
 * 적어 보내는 쪽이 정상 사용자의 통을 비울 수 있기 때문이다). 창 하나의 값은 그 10분 동안
 * 상수이므로, 한 번 계산해 들고 있으면 그 증폭이 사라진다.
 * **그래서 이 캐시의 크기는 창 수와 묶여 있다** — 아래 `WINDOW_TOKEN_CACHE_MAX` 참고.
 *
 * 새로 드러나는 것은 없다 — 여기 담기는 값은 서버가 응답마다 헤더로 실어 보내는 바로 그
 * 문자열이고, 비밀값 자체는 담지 않는다(바뀌면 통째로 버린다).
 */
const windowTokens = new Map<number, string>();
let cachedSecret: string | undefined;

/**
 * 캐시 크기는 **stale 창 수에서 계산해 냅니다** — 두 수가 갈라지지 않게.
 *
 * 결합의 근거: 어긋난 표식 한 건은 창을 `COACH_TOKEN_STALE_WINDOWS`개까지 거슬러 대조하고,
 * 그 경로는 **예산을 쓰지 않습니다**(값이 어긋난 요청에 예산을 물리면 표식을 아무렇게나 적어
 * 보내는 쪽이 정상 사용자의 통을 비울 수 있기 때문입니다 — `route.ts`의 열거 ①).
 * 캐시가 창 수보다 작으면 그 무예산 경로가 **요청당 HMAC N번짜리 증폭기**가 됩니다.
 * 그래서 두 수를 손으로 적지 않고 하나에서 뽑습니다 — 8과 6이 각자 적혀 있던 동안, 다음 사람이
 * 창 수만 올리면 그 증폭기가 조용히 열리는 상태였습니다(7차 페르소나 백엔드 low).
 * 여유 넷은 창이 넘어가는 순간(현재 창 + 대조 중인 옛 창들)의 겹침 몫입니다.
 */
const WINDOW_TOKEN_CACHE_MAX = COACH_TOKEN_STALE_WINDOWS + 4;

/**
 * 창 하나의 토큰 — `HMAC-SHA256(창 번호, 비밀값)`의 앞 16자.
 *
 * Web Crypto만 씁니다(node:crypto를 import하지 않습니다) — 서버 렌더와 라우트가 같은 함수를
 * 쓰고, 회귀 검사도 같은 함수를 그대로 태웁니다.
 */
export async function coachToken(secret: string, window: number): Promise<string> {
  if (secret !== cachedSecret) {
    cachedSecret = secret;
    windowTokens.clear();
  }
  const remembered = windowTokens.get(window);
  if (remembered !== undefined) return remembered;

  const encoder = new TextEncoder();
  const key = await crypto.subtle.importKey(
    "raw",
    encoder.encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const signature = await crypto.subtle.sign("HMAC", key, encoder.encode(String(window)));
  const value = toHex(signature).slice(0, COACH_TOKEN_LENGTH);

  windowTokens.set(window, value);
  if (windowTokens.size > WINDOW_TOKEN_CACHE_MAX) {
    /* 퇴출은 **가장 작은 창 번호** 기준입니다 — 삽입 순서가 아닙니다.
       Map은 삽입 순서를 지키지만, 담는 쪽인 `coachTokenWindowAge`는 `window - age`를 age 0부터
       올려 가며 부르므로 창 번호를 **내림차순**으로 담습니다. 그래서 「먼저 담긴 것이 가장 낡은
       것」이라는 예전 주석은 어긋난 표식 한 건이 캐시를 채우는 경로에서 거짓이었고, 그 상태로
       퇴출이 걸리면 지워지는 것이 그중 가장 **새** 창이었습니다(7차 페르소나 백엔드 low).
       지금 값에서는 워밍업 몇 번으로 끝나 실해가 없었지만, 그 사실이 사실이 아닌 주석과 함께
       남아 있으면 다음 사람이 이 자리를 「이미 맞다」로 읽습니다. */
    let oldest: number | undefined;
    for (const key of windowTokens.keys()) {
      if (oldest === undefined || key < oldest) oldest = key;
    }
    if (oldest !== undefined) windowTokens.delete(oldest);
  }
  return value;
}

/**
 * `<meta>`에 심는 값 — `창번호.토큰`.
 *
 * 창 번호를 함께 적는 이유는 화면 쪽이 **낡은 토큰을 스스로 걷어 내기 위해서**다. 낡은 값을
 * 그대로 보내면 403을 받고 조용히 검수 코칭으로 접히는데, 창 번호가 있으면 그 전에 헤더를 빼고
 * 보내 작은 예산 통으로 넘어간다(훈련이 끊기지 않는다). 창 번호는 비밀이 아니다(그냥 시각이다).
 *
 * **문서에 심긴 이 값은 첫 한 번의 씨앗일 뿐이다.** 앱 안 이동은 서버 렌더를 다시 타지 않으므로
 * 한 판을 길게 훈련하면 이 값이 창을 넘어서는데, 그다음부터는 라우트가 응답 헤더로 돌려주는
 * 최신 값이 이 자리를 대신한다(`COACH_TOKEN_REFRESH_HEADER`). 같은 꼴이라 읽는 함수도 하나다.
 */
export async function coachTokenMetaValue(
  secret: string,
  now: number = Date.now(),
): Promise<string> {
  const window = coachTokenWindow(now);
  return `${window}.${await coachToken(secret, window)}`;
}

/** 길이가 같은 두 문자열을 **끝까지** 비교한다(빨리 빠져나가지 않는다). */
function sameToken(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i += 1) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

/**
 * 받은 토큰이 **몇 창 전**의 값인지 — 지금 창이면 0, 어느 창과도 맞지 않으면 `undefined`.
 *
 * `windows`만큼만 거슬러 봅니다. 두 부름이 있습니다 — 정상 예산 통을 가르는 `verifyCoachToken`은
 * 두 창까지, 갱신 표식을 내줄지 가르는 라우트는 `COACH_TOKEN_STALE_WINDOWS`까지(사유는 그 상수).
 *
 * 담는 순서 주의: `window - age`를 age 0부터 올려 가며 부르므로 캐시에는 창 번호가 **내림차순**
 * 으로 들어갑니다(`coachToken`의 퇴출이 그 사실을 봅니다).
 */
async function coachTokenWindowAge(
  secret: string,
  value: string,
  now: number,
  windows: number,
): Promise<number | undefined> {
  if (secret.length === 0 || value.length !== COACH_TOKEN_LENGTH) return undefined;
  const window = coachTokenWindow(now);
  for (let age = 0; age < windows; age += 1) {
    if (sameToken(value, await coachToken(secret, window - age))) return age;
  }
  return undefined;
}

/**
 * 받은 토큰이 **현재 창이나 직전 창**의 값인지 — 정상 예산 통을 쓸 자격이다.
 *
 * @example
 * const token = await coachToken(secret, coachTokenWindow());
 * await verifyCoachToken(secret, token); // true
 */
export async function verifyCoachToken(
  secret: string,
  value: string,
  now: number = Date.now(),
): Promise<boolean> {
  return (await coachTokenWindowAge(secret, value, now, COACH_TOKEN_FRESH_WINDOWS)) !== undefined;
}

/**
 * 받은 토큰이 **갱신을 받을 자격**이 있는지 — 서른여섯 창(6시간) 안의 값이면 참.
 *
 * 수치를 여기 두 번 적지 말 것: 실제로 세는 값은 `COACH_TOKEN_STALE_WINDOWS` 하나이고, 이 줄은
 * 그 값을 사람 말로 옮긴 것뿐이다. 창 수를 6에서 36으로 넓힌 뒤에도 이 줄만 「여섯 창(60분)」으로
 * 남아 있었다 — 이 파일이 다루는 것이 보안 통제 수치라, 사고가 났을 때 사람이 먼저 읽는 것이
 * 상수가 아니라 이 문장이다(9차 임원평가 CTO low).
 *
 * 「정상 통을 쓸 자격」(위)과 갈라 둔 자리다. 여기서 참이지만 위에서 거짓인 표식은 **작은 통을
 * 쓰되 갱신 표식은 받는다** — 탭을 오래 열어 둔 화면이 영영 작은 통에 남지 않게 하면서,
 * 표식을 한 번도 가진 적 없는 호출자에게는 아무것도 주지 않는 자리입니다.
 *
 * @example
 * await isRenewableCoachToken(secret, await coachToken(secret, coachTokenWindow() - 4)); // true
 */
export async function isRenewableCoachToken(
  secret: string,
  value: string,
  now: number = Date.now(),
): Promise<boolean> {
  return (await coachTokenWindowAge(secret, value, now, COACH_TOKEN_STALE_WINDOWS)) !== undefined;
}
