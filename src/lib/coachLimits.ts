/**
 * `/api/coach`에 얹는 **단기 토큰** — 인증이 아니라 「이 앱의 화면에서 왔다」는 표식이다.
 *
 * 무엇을 푸는가: 출처 검사(`Sec-Fetch-Site`·`Origin`)는 **브라우저가 지키는 경계**라, 헤더를
 * 손으로 적을 수 있는 도구 앞에서는 그대로 통과한다(실측으로 확인된 사실이다). 그 결과 남는
 * 유일한 벽이 배포 전체 상한이었고, 그 벽은 곧 서비스를 끄는 스위치였다.
 *
 * 어떻게 푸는가: 서버가 페이지를 그릴 때 `HMAC-SHA256(현재 창 번호, 비밀값)`의 앞 16자를
 * `<meta>`로 심고, 화면의 fetch 세 자리가 그 값을 `x-chimchak-key` 헤더로 되돌려 보낸다.
 * 서버가 가르는 것은 셋이다 — **현재 창과 직전 창**이면 정상 예산 통,
 * 그보다 낡았지만 `COACH_TOKEN_STALE_WINDOWS` 안이면 작은 통을 쓰되 **갱신 표식은 받고**,
 * 어느 창과도 맞지 않으면 계수기에 닿기 전에 403이다.
 * 값이 아예 없는 요청은 막지 않고 작은 예산 통으로 보낸다(옛 클라이언트가 그대로 동작한다).
 *
 * 무엇을 풀지 못하는가: 페이지를 한 번 받아 토큰을 긁어 가는 스크립트는 여전히 막지 못한다.
 * 창이 지나면 그 토큰이 죽는다는 것이 이 장치가 파는 전부이고, 그래서 이름을 「비밀 헤더」로
 * 두지 않고 **표식**이라고 적어 둔다. 어느 배포에서든 참인 방어선은 상류 계정의 지출 상한이다.
 *
 * 비밀값이 없으면 이 장치는 **통째로 잠든다** — 파일럿을 세우지 않기 위한 규칙이다.
 */
export const COACH_TOKEN_HEADER = "x-chimchak-key";

/** 서버 렌더가 토큰을 심는 `<meta name>` — 화면과 서버가 같은 문자열을 본다. */
export const COACH_TOKEN_META = "chimchak-k";

/**
 * 라우트가 **응답에** 실어 돌려주는 다음 토큰 — 갱신 경로다.
 *
 * 왜 필요한가: 토큰을 심는 자리가 서버 렌더 하나뿐이면 **문서 수명이 곧 토큰 수명**이 된다.
 * 이 앱은 화면 이동이 전부 앱 안 라우팅이고(루트 레이아웃을 다시 그리지 않는다) 홈 화면에
 * 설치해 쓰는 형태라, 09:00에 연 문서로 09:20 이후 훈련하면 심어 둔 값이 창 둘을 넘어선다.
 * 그때 화면은 스스로 헤더를 빼고(낡은 값은 403이므로) **무토큰 통**으로 넘어간다 — 예산을
 * 둘로 나눈 목적(「작은 통이 말라도 정상 사용자의 통은 그대로 돈다」)이 정확히 뒤집히고,
 * 서비스를 하루 끄는 문턱이 `defaultDailyCap`에서 `anonDailyCap`으로 내려앉는다.
 *
 * 그래서 라우트는 **받아들인 요청마다** 지금 창의 값을 이 헤더로 되돌려 주고, 화면은 그것을
 * 모듈 캐시에 담아 다음 요청부터 `<meta>`보다 **먼저** 쓴다(`src/lib/onlineCoach.ts`).
 * 심는 자리가 「서버 렌더 한 번」에서 「매 호출」로 옮겨 가므로, 한 판을 두 시간 돌려도
 * 정상 통에 남는다.
 *
 * 값의 꼴은 `<meta>`와 **똑같다**(`창번호.토큰`) — 화면이 두 자리를 같은 함수로 읽는다.
 *
 * **누가 받는가**: 이미 **표식을 들고 온 요청**뿐이다(지금 창이든 낡은 창이든). 표식을 한 번도
 * 가진 적 없는 요청은 이 헤더를 받지 못한다.
 *
 * 그렇게 좁힌 이유: 예전에는 무토큰 요청에도 붙였고, 그러면 몸통이 틀린 30바이트 POST 한 번의
 * 400 응답에서 표식이 나왔다. 작은 예산 통이 「**1회 통행료**」가 되던 자리다 — 스크립트가
 * 작은 통 한 칸만 쓰고 나머지 전량을 큰 통에서 태울 수 있었고, 매 응답이 표식을 다시 실어
 * 주므로 재취득도 필요 없었다. 아래 「더 싸게 주지 않는다」가 그 경로에서만 거짓이었다.
 *
 * 공격면이 넓어지지 않는 이유: 이 토큰은 인증이 아니라 「이 앱의 화면에서 왔다」는 **표식**이고,
 * 페이지 HTML을 한 번 받아 `<meta>`를 긁는 쪽은 예전에도 같은 값을 얻었다(위 문단에 이미 적어
 * 둔 한계다). 갱신 헤더는 그 값을 **더 싸게** 주지 않는다 — 헤더를 받으려면 이미 유효한 표식을
 * 들고 와야 하고, 그 표식을 처음 얻는 길은 예나 지금이나 페이지를 받는 것뿐이다.
 * 어긋난 표식(403)·출처가 다른 요청·무토큰 요청·`ping`에는 이 헤더를 붙이지 않는다.
 *
 * 비밀값이 없는 배포에서는 **헤더 자체가 없다** — 응답 한 글자도 예전과 다르지 않다.
 */
export const COACH_TOKEN_REFRESH_HEADER = "x-chimchak-key-next";

